import fs from 'node:fs';
import path from 'node:path';
const root = process.cwd();
const read = (p) => fs.readFileSync(path.join(root, p), 'utf8');
const api = read('src/lib/accountDeletionApi.ts');
const policy = read('src/lib/accountDeletionPolicy.ts');
const gate = read('src/components/AccountDeletionGate.tsx');
const checks = [];
const check = (name, ok) => checks.push({ name, ok: Boolean(ok) });
check('get uses canonical deletion RPC', api.includes("hc_jobseeker_get_account_deletion_request_v1"));
check('request uses canonical deletion RPC', api.includes("hc_jobseeker_request_account_deletion_v1"));
check('cancel uses canonical deletion RPC', api.includes("hc_jobseeker_cancel_account_deletion_v1"));
check('unknown server status is rejected', api.includes('statuses.has(value.status as AccountDeletionStatus)'));
check('requested blocks business UI', /status === 'requested'[\s\S]*blocksBusinessUi: true/.test(policy));
check('requested quarantines device state', /status === 'requested'[\s\S]*quarantineCandidateDeviceState: true/.test(policy));
check('requested can be cancelled', /status === 'requested'[\s\S]*canCancel: true/.test(policy));
check('cancelled restores business UI', /!status \|\| status === 'cancelled'[\s\S]*blocksBusinessUi: false/.test(policy));
check('gate has requested full-screen state', gate.includes('testID="account-deletion-requested"'));
check('requested gate explains mutations are stopped', gate.includes('応募・メッセージ・保存・書類更新・Push再登録は行いません。'));
check('requested gate exposes cancellation', gate.includes('削除を取り消す') && gate.includes('run(onCancel)'));
check('processing blocks business UI', gate.includes('testID="account-deletion-processing"'));
check('failed blocks business UI', gate.includes('testID="account-deletion-failed"'));
check('completed is terminal UI', gate.includes('testID="account-deletion-completed"'));
check('normal children render only when policy allows', gate.includes('if (!policy.blocksBusinessUi) return <>{children}</>;'));
check('async button failures are swallowed for provider-owned error state', gate.includes("Promise.resolve(action()).catch(() => undefined)"));
const failed = checks.filter((x) => !x.ok);
console.log(JSON.stringify({ total: checks.length, passed: checks.length - failed.length, failed }, null, 2));
if (failed.length) process.exit(1);
