import fs from 'node:fs';
const read=(p)=>fs.readFileSync(new URL('../'+p, import.meta.url),'utf8');
const index=read('public/guides/index.html');
const article=read('public/guides/hoikushi-tenshoku-mensetsu-shitsumon/index.html');
const sitemap=read('public/sitemap.xml');
const robots=read('public/robots.txt');
const required=(body,needle,label)=>{if(!body.includes(needle))throw new Error('SEO guide contract: '+label);};
required(index,'<meta name="robots" content="index,follow','guide index must be indexable');
required(index,'rel="canonical" href="https://app.hoikucolor.jp/guides/"','guide index canonical');
required(article,'<meta name="robots" content="index,follow','article must be indexable');
required(article,'rel="canonical" href="https://app.hoikucolor.jp/guides/hoikushi-tenshoku-mensetsu-shitsumon/"','article canonical');
required(article,'"@type":"Article"','Article JSON-LD');
required(article,'"@type":"BreadcrumbList"','Breadcrumb JSON-LD');
required(article,'href="/jobs"','job-search CTA');
required(article,'https://kouseisaiyou.mhlw.go.jp/jobseekers.html','primary source');
required(sitemap,'/guides/hoikushi-tenshoku-mensetsu-shitsumon/','article sitemap entry');
required(robots,'Sitemap: https://app.hoikucolor.jp/sitemap.xml','robots sitemap declaration');
if(/noindex/i.test(article))throw new Error('SEO guide contract: article unexpectedly noindex');
console.log('SEO guide contract PASS');
